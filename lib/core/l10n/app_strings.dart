/// ترجمة التطبيق + دعم اللغتين والاتجاه.
class AppLocalizations {
  const AppLocalizations(this.locale);

  final Locale locale;

  static const List<Locale> supportedLocales = <Locale>[Locale('ar'), Locale('en')];

  static const LocalizationsDelegate<AppLocalizations> delegate = _AppLocalizationsDelegate();

  bool get isArabic => locale.languageCode == 'ar';

  String get lang => locale.languageCode;

  bool get isRtl => isArabic;

  /// ترجمة مفتاح، مع تعويض القيم داخل {} عند الحاجة.
  String t(String key, [Map<String, String>? args]) {
    final Map<String, String> primary = isArabic ? L.ar : L.en;
    final Map<String, String> fallback = isArabic ? L.en : L.ar;
    String value = primary[key] ?? fallback[key] ?? key;
    if (args != null && args.isNotEmpty) {
      args.forEach((String k, String v) {
        value = value.replaceAll('{$k}', v);
      });
    }
    return value;
  }

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations) ??
      const AppLocalizations(Locale('ar'));

  static AppLocalizations ofLocale(Locale locale) => AppLocalizations(locale);
}

class _AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => locale.languageCode == 'ar' || locale.languageCode == 'en';

  @override
  Future<AppLocalizations> load(Locale locale) async => AppLocalizations(locale);

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

/// اختصارات للوصول السريع للترجمة من أي واجهة.
extension L10nX on BuildContext {
  String tr(String key, [Map<String, String>? args]) => AppLocalizations.of(this).t(key, args);

  bool get isArabic => AppLocalizations.of(this).isArabic;

  String get langCode => AppLocalizations.of(this).lang;
}
